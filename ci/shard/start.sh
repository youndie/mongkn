#!/usr/bin/env bash
# Запускает минимальный шардированный кластер: конфигурационный реплика-сет, два шарда, mongos.
#
# **Четыре процесса — это и есть минимум.** Шард обязан быть реплика-сетом (standalone сервер
# в качестве шарда сервер не принимает), конфигурация кластера живёт в отдельном реплика-сете,
# а клиент ходит через mongos. Второй шард нужен не для симметрии: без него нечем проверить
# ни распределение документов, ни слияние результатов на mongos — то есть всё, ради чего
# шардированный контур и заводится.
#
# Все четыре живут **в одном контейнере**, и это осознанно:
#
# * адреса. Член реплика-сета объявляет себя тем адресом, который записан в его конфигурации,
#   и по этому адресу к нему приходит mongos. Внутри одного контейнера это `127.0.0.1:<порт>` —
#   ровно то же, что и при запуске четырёх процессов на машине без docker (macOS-раннер в CI).
#   Одна раскладка адресов на оба случая означает один скрипт инициализации, а не два похожих;
# * память. Вопрос «сколько стоит шардированный контур» имеет ответ одним числом, а не суммой
#   четырёх лимитов, которые по отдельности ничего не значат.
#
# Клиенту наружу видна только mongos: он один и объявлен точкой входа, шарды и конфигурация
# драйверу не адресуются никогда.
#
# Переменные:
#   MONGKN_SHARD_DBROOT      — куда класть данные (по умолчанию /data/shard);
#   MONGKN_SHARD_FOREGROUND  — 1, если mongos должен остаться на переднем плане (контейнер).
set -euo pipefail

ROOT="${MONGKN_SHARD_DBROOT:-/data/shard}"

# Порты фиксированы и одинаковы внутри контейнера и на macOS-раннере — см. шапку.
# Наружу публикуется только CLUSTER_PORT.
# Порты берутся из окружения со сдвигом MONGKN_PORT_OFFSET. Внутри контейнера сдвиг не нужен
# и равен нулю, а вот на машине **без** docker (macOS-раннер) все четыре процесса живут
# на хостовых портах — и там контур прогона обязан разъехаться с контуром разработчика.
OFFSET="${MONGKN_PORT_OFFSET:-0}"
CONFIG_PORT=$((27031 + OFFSET))
SHARD_A_PORT=$((27032 + OFFSET))
SHARD_B_PORT=$((27033 + OFFSET))
CLUSTER_PORT=$((27021 + OFFSET))

# Четверть гигабайта на узел — тот же минимум, что и у остальных тестовых серверов: по умолчанию
# WiredTiger забрал бы половину ОЗУ машины на **каждый** из трёх mongod.
#
# `periodicNoopIntervalSecs` — не тонкая настройка, а условие вменяемого времени прогона.
# На шардированном кластере mongos отдаёт событие потока изменений только тогда, когда **все**
# шарды доложили, что дошли до этого момента времени; на молчащем шарде такой доклад приносит
# периодическая пустая запись, а она по умолчанию раз в 10 секунд. С умолчанием тест на `watch`
# ждёт полминуты и выглядит подвисшим — измерено, было 17 секунд на два события.
start_mongod() {
  local name="$1" port="$2" role="$3" replica_set="$4"
  mkdir -p "$ROOT/$name"
  mongod \
    --port "$port" "$role" --replSet "$replica_set" \
    --dbpath "$ROOT/$name" --bind_ip_all \
    --wiredTigerCacheSizeGB 0.25 \
    --setParameter enableTestCommands=1 \
    --setParameter periodicNoopIntervalSecs=1 \
    --fork --logpath "$ROOT/$name.log"
}

start_mongod cfg "$CONFIG_PORT" --configsvr mongkn-cfg
start_mongod a "$SHARD_A_PORT" --shardsvr mongkn-a
start_mongod b "$SHARD_B_PORT" --shardsvr mongkn-b

# mongos поднимается **до** инициализации конфигурационного реплика-сета и это не гонка:
# он не падает от недоступной конфигурации, а повторяет попытки, пока `rs.initiate` из init.sh
# не отработает. Проверено прогоном — иначе пришлось бы разносить старт и инициализацию
# по разным местам и объяснять их порядок.
mongos_args=(
  --port "$CLUSTER_PORT"
  --configdb "mongkn-cfg/127.0.0.1:$CONFIG_PORT"
  --bind_ip_all
  --setParameter enableTestCommands=1
)

if [ "${MONGKN_SHARD_FOREGROUND:-0}" = "1" ]; then
  # В контейнере mongos обязан быть на переднем плане: он же и признак живости кластера.
  exec mongos "${mongos_args[@]}"
else
  # Ветка для машины без docker (macOS-раннер): процессы отвязываются и живут дальше сами.
  # Запускать её **через `docker exec`** не стоит — вызов не вернётся: forked-процессы держат
  # открытым унаследованный stdout, и docker ждёт его закрытия. В контейнере есть ветка выше.
  #
  # `--fork` здесь **недопустим**, хотя для mongod он и используется выше. Разница в том, когда
  # процесс объявляет себя готовым: mongod готов сразу, а mongos — только договорившись
  # с конфигурационным реплика-сетом. А тот инициализирует `init.sh`, который запускается уже
  # после этого скрипта. Получалась взаимная блокировка: mongos ждёт конфигурацию, конфигурацию
  # ждёт скрипт, который не запустится, пока не вернётся mongos. На macOS-раннере джоба висела
  # на этом почти час и молча — форк не печатает ничего, пока не готов.
  #
  # Готовности mongos дожидается сам `init.sh` (`wait_for_port "$CLUSTER_PORT"`), поэтому здесь
  # достаточно отвязать процесс и отдать управление.
  nohup mongos "${mongos_args[@]}" >>"$ROOT/mongos.log" 2>&1 &
  disown
fi
