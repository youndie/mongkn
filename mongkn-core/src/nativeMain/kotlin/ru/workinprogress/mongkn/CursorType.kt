package ru.workinprogress.mongkn

/**
 * Поведение курсора после того, как документы кончились.
 *
 * Обычный курсор на этом закрывается. Tailable остаётся открытым и ждёт новых документов —
 * имеет смысл только на capped-коллекциях.
 */
public enum class CursorType {
    /** Закрыться, когда документы кончились. Так ведёт себя `find` по умолчанию. */
    NON_TAILABLE,

    /** Остаться открытым, но не ждать: `next` вернёт «пусто» сразу. */
    TAILABLE,

    /** Остаться открытым и ждать новых документов — см. [FindFlow.maxAwaitTime]. */
    TAILABLE_AWAIT,
}
